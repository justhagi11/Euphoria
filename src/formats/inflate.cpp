std::expected<std::size_t, std::string_view> zlib_inflate(std::span<const std::uint8_t> source,
                                                          std::span<std::uint8_t> destination)
{
    if (source.size() < 6) {
        return std::unexpected(Error{"stream is too short"});
    }
    const std::uint32_t cmf = source[0];
    const std::uint32_t flags = source[1];
    if ((cmf & 15u) != 8 || (cmf >> 4) > 7 || (flags & 0x20u) != 0 || ((cmf << 8) | flags) % 31 != 0) {
        return std::unexpected(Error{"invalid zlib header"});
    }
    BitReader reader{source.subspan(2)};
    std::size_t at = 0;
    bool last = false;
    auto trees = std::make_unique<Trees>();
    while (!last) {
        last = reader.take(1) != 0;
        const std::uint32_t type = reader.take(2);
        if (reader.overrun()) {
            return std::unexpected(Error{"stream is truncated"});
        }
        if (type == 0) {
            reader.align();
            const std::uint32_t length = reader.take(16);
            const std::uint32_t inverse = reader.take(16);
            if (reader.overrun()) {
                return std::unexpected(Error{"stream is truncated"});
            }
            if ((length ^ 0xffffu) != inverse) {
                return std::unexpected(Error{"stored block length mismatch"});
            }
            if (length > destination.size() - at) {
                return std::unexpected(Error{"output larger than destination"});
            }
            if (!reader.copy_bytes(destination.data() + at, length)) {
                return std::unexpected(Error{"stream is truncated"});
            }
            at += length;
            continue;
        }
        if (type == 1) {
            if (!fixed_trees(*trees)) {
                return std::unexpected(Error{"fixed trees failed"});
            }
        } else if (type == 2) {
            if (!dynamic_trees(reader, *trees)) {
                return std::unexpected(Error{"invalid dynamic trees"});
            }
        } else {
            return std::unexpected(Error{"invalid block type"});
        }
        if (auto result = inflate_block(reader, *trees, destination, at); !result) {
            return std::unexpected(result.error());
        }
    }
    reader.align();
    std::uint32_t expected = 0;
    for (int k = 0; k < 4; ++k) {
        expected = (expected << 8) | reader.take(8);
    }
    if (reader.overrun()) {
        return std::unexpected(Error{"stream is truncated"});
    }
    if (adler32(destination.first(at)) != expected) {
        return std::unexpected(Error{"checksum mismatch"});
    }
    return at;
}

