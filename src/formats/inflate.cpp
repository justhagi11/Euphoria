int inflate_self_test(std::string& report)
{
    int failures = 0;
    const auto check = [&](std::string_view name, bool ok) {
        report += std::format("{} {}\n", ok ? "ok  " : "FAIL", name);
        if (!ok) {
            ++failures;
        }
    };

    const auto plain = pattern(65537);
    check("inflate exact fit", inflates_to(kPatternZlib, plain));

    {
        std::vector<std::uint8_t> larger(plain.size() + 64, 0xaa);
        const auto result = zlib_inflate(kPatternZlib, std::span<std::uint8_t>{larger.data(), plain.size() + 32});
        const bool guard = std::all_of(larger.begin() + static_cast<std::ptrdiff_t>(plain.size()) + 32,
                                       larger.end(), [](std::uint8_t b) { return b == 0xaa; });
        check("inflate short stream into larger destination",
              result && *result == plain.size()
                  && std::equal(plain.begin(), plain.end(), larger.begin()) && guard);
    }

    {
        std::array<std::uint8_t, 4> scratch{0x55, 0x55, 0x55, 0x55};
        const auto empty_out = zlib_inflate(kEmptyZlib, std::span<std::uint8_t>{});
        const auto scratch_out = zlib_inflate(kEmptyZlib, scratch);
        check("inflate empty stream", empty_out && *empty_out == 0 && scratch_out && *scratch_out == 0);
    }

    {
        std::vector<std::uint8_t> small(plain.size() - 1);
        check("inflate rejects oversized output",
              fails(kPatternZlib, small) && fails(kPatternZlib, std::span<std::uint8_t>{}));
    }

    {
        std::vector<std::uint8_t> out(plain.size());
        const std::span<const std::uint8_t> packed{kPatternZlib};
        check("inflate rejects truncated streams",
              fails(packed.first(packed.size() - 1), out) && fails(packed.first(packed.size() / 2), out)
                  && fails({}, out));
    }

    {
        std::vector<std::uint8_t> out(plain.size());
        std::vector<std::uint8_t> bad_adler(std::begin(kPatternZlib), std::end(kPatternZlib));
        bad_adler.back() ^= 1;
        std::vector<std::uint8_t> bad_body(std::begin(kPatternZlib), std::end(kPatternZlib));
        bad_body[2] ^= 0xff;
        check("inflate rejects corrupt streams",
              fails(bad_adler, out) && fails(bad_body, out) && inflates_to(kPatternZlib, plain));
    }

    check("inflate stored blocks", inflates_to(kStoredZlib, pattern(300)));

    {
        const auto data = skewed(8000);
        std::vector<std::uint8_t> reference;
        const bool decoded = openscarlett::zlib_rfc1950::Decompress(kSkewedZlib, sizeof(kSkewedZlib),
                                                                    data.size(), reference);
        check("inflate long codes match openscarlett",
              inflates_to(kSkewedZlib, data) && decoded && reference == data);
    }

    {
        std::vector<std::uint8_t> padded(std::begin(kPatternZlib), std::end(kPatternZlib));
        padded.insert(padded.end(), 16, 0);
        check("inflate ignores trailing input", inflates_to(padded, plain));
    }

    return failures;
}

