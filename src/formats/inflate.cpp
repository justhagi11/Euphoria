std::vector<std::uint8_t> pattern(std::size_t n)
{
    std::vector<std::uint8_t> out(n);
    for (std::size_t i = 0; i < n; ++i) {
        out[i] = static_cast<std::uint8_t>(i * 7 + i / 251);
    }
    return out;
}

std::vector<std::uint8_t> skewed(std::size_t n)
{
    std::uint64_t x = 0x9e3779b97f4a7c15ull;
    std::vector<std::uint8_t> out(n);
    for (auto& value : out) {
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        const std::uint64_t y = x | (1ull << 40);
        unsigned zeros = 0;
        while (((y >> zeros) & 1u) == 0) {
            ++zeros;
        }
        value = static_cast<std::uint8_t>(zeros * 9 + (x >> 61));
    }
    return out;
}

bool inflates_to(std::span<const std::uint8_t> source, const std::vector<std::uint8_t>& plain)
{
    std::vector<std::uint8_t> out(plain.size());
    const auto result = zlib_inflate(source, out);
    return result && *result == plain.size() && out == plain;
}

bool fails(std::span<const std::uint8_t> source, std::span<std::uint8_t> out)
{
    return !zlib_inflate(source, out).has_value();
}

