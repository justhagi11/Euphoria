std::vector<std::uint32_t> cmpx_waterfall(bool wave64, bool folded)
{
    const std::span<const std::uint32_t> base = wave64 ? std::span<const std::uint32_t>{kWATERFALL_FETCHED_WAVE64}
                                                       : std::span<const std::uint32_t>{kWATERFALL_JOINED_WAVE32};
    const std::uint32_t todo = wave64 ? 0xBE94047Eu : 0xBE97037Eu;
    const std::uint32_t restore = wave64 ? 0xBEFE0414u : 0xBEFE0317u;
    const std::size_t reads = word_at(base, 0x7E180504u);
    const std::size_t sample = word_at(base, 0xF09C0F08u);
    std::vector<std::uint32_t> w(base.begin(), base.begin() + static_cast<std::ptrdiff_t>(word_at(base, todo) + 1));
    w.push_back(wave64 ? 0xBE96047Eu : 0xBE95037Eu);
    w.insert(w.end(), base.begin() + static_cast<std::ptrdiff_t>(reads),
             base.begin() + static_cast<std::ptrdiff_t>(reads + 8));
    w.insert(w.end(), {0x7DE4080Cu, 0x7DE40C0Eu, 0x7DE41010u, 0x7DE41412u});
    w.insert(w.end(), base.begin() + static_cast<std::ptrdiff_t>(sample),
             base.begin() + static_cast<std::ptrdiff_t>(sample + 2));
    if (!wave64 && folded) {
        w.insert(w.end(), {0xBE954715u, 0xBF89FFF0u});
    } else if (!wave64) {
        w.insert(w.end(), {0x8A157E15u, 0xBEFE0315u, 0xBF89FFEFu});
    } else if (folded) {
        w.insert(w.end(), {0xBE963A16u, 0xBF89FFF0u});
    } else {
        w.insert(w.end(), {0x8A967E16u, 0xBEFE0416u, 0xBF89FFEFu});
    }
    w.insert(w.end(), base.begin() + static_cast<std::ptrdiff_t>(word_at(base, restore)), base.end());
    return w;
}

